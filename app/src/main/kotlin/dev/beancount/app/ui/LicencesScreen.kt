/**
 * One thing the app distributes, and the licence that came with it.
 *
 * [text] is the licence as it was actually shipped by that component wherever it ships one,
 * rather than a canonical copy chosen by us — see [loadLicences].
 */
data class LicenceEntry(
    val name: String,
    val version: String,
    val text: String,
    val source: String,
    val members: List<String>,
)

/**
 * Reads `assets/licences.json`, generated by `tools/licences.py` from a built APK.
 *
 * Generated rather than hand-written for the same reason the SBOM is: a list of dependencies
 * maintained by a person is a list that stops being true, and here that is not a tidiness
 * problem but a licence-compliance one. CI regenerates it from the APK and fails if the
 * committed copy has drifted.
 */
fun loadLicences(context: Context): Pair<LicenceEntry, List<LicenceEntry>> {
    val root = JSONObject(
        context.assets.open("licences.json").bufferedReader().use { it.readText() },
    )

    val app = root.getJSONObject("app")
    val self = LicenceEntry(
        name = app.getString("name"),
        version = app.getString("licence"),
        text = app.getString("text"),
        source = app.getString("note"),
        members = emptyList(),
    )

    val array = root.getJSONArray("components")
    val components = (0 until array.length()).map { index ->
        val entry = array.getJSONObject(index)
        val members = entry.optJSONArray("members")
        LicenceEntry(
            name = entry.getString("name"),
            version = entry.getString("version"),
            text = entry.getString("text"),
            source = entry.getString("source"),
            members = (0 until (members?.length() ?: 0)).map { members!!.getString(it) },
        )
    }
    return self to components
}

/**
 * The licences, where a user can actually read them.
 *
 * This app is GPL-2.0-only and bundles 36 Python packages and 29 Android libraries under MIT,
 * BSD, X11, LGPL-2.1, PSF, Apache-2.0, EPL and CC0. Every one of those requires its notice to
 * travel with the software, and the GPL requires the terms be offered to the user. Shipping
 * the bytes inside a zip inside `assets/`, which is what happened until M14, is a thin reading
 * of both (docs/milestones/m14-part11.md).
 *
 * The app's own licence comes first and is stated in plain words before the legal text,
 * because "you may use, study, share and change this" is the part that means something to
 * someone who is not a lawyer, and it is the part a GPL app most owes its users.
 */
@Composable
fun LicencesScreen(modifier: Modifier = Modifier) {
    val context = LocalContext.current
    val (app, components) = remember { loadLicences(context) }
    var showing by remember { mutableStateOf<LicenceEntry?>(null) }

    showing?.let { entry ->
        LicenceText(entry = entry, onBack = { showing = null }, modifier = modifier)
        return
    }

    LazyColumn(modifier = modifier) {
        item {
            Column(
                Modifier.padding(16.dp),
                verticalArrangement = Arrangement.spacedBy(8.dp),
            ) {
                Text(
                    "Licences",
                    style = MaterialTheme.typography.titleMedium,
                    modifier = Modifier.semantics { heading() },
                )
                Card(
                    modifier = Modifier
                        .fillMaxWidth()
                        .clickable { showing = app }
                        .semantics {
                            contentDescription =
                                "${app.name} is under ${app.version}. Read the full licence."
                        },
                    colors = CardDefaults.cardColors(
                        containerColor = MaterialTheme.colorScheme.secondaryContainer,
                    ),
                ) {
                    Column(
                        Modifier.padding(12.dp),
                        verticalArrangement = Arrangement.spacedBy(6.dp),
                    ) {
                        Text("${app.name} — ${app.version}", style = MaterialTheme.typography.titleSmall)
                        Text(app.source, style = MaterialTheme.typography.bodySmall)
                        Text("Read the full licence", style = MaterialTheme.typography.labelLarge)
                    }
                }
                Text(
                    "This app is built on other people's work. Each of these came with a " +
                        "licence, and each licence is here in full.",
                    style = MaterialTheme.typography.bodySmall,
                )
            }
        }

        items(components, key = { "${it.kind()}:${it.name}" }) { entry ->
            ListItem(
                headlineContent = { Text(entry.name) },
                supportingContent = { Text(entry.version) },
                modifier = Modifier
                    .clickable { showing = entry }
                    .semantics {
                        contentDescription = "${entry.name}, ${entry.version}. Read its licence."
                    },
            )
            HorizontalDivider()
        }
    }
}

private fun LicenceEntry.kind() = if (members.isEmpty()) "component" else "group"

/**
 * A licence, in full and unaltered.
 *
 * Monospace and horizontally scrollable because these texts are written to a fixed column
 * width, and reflowing them makes the numbered clauses of the GPL and the Apache licence
 * hard to follow. The row scrolls; the page does not (CLAUDE.md, responsive rules).
 */
@Composable
private fun LicenceText(entry: LicenceEntry, onBack: () -> Unit, modifier: Modifier = Modifier) {
    Column(modifier = modifier.padding(16.dp), verticalArrangement = Arrangement.spacedBy(8.dp)) {
        TextButton(
            onClick = onBack,
            modifier = Modifier.semantics { contentDescription = "Back to the list of licences" },
        ) { Text("← All licences") }

        Text(
            "${entry.name} — ${entry.version}",
            style = MaterialTheme.typography.titleMedium,
            modifier = Modifier.semantics { heading() },
        )
        Text(entry.source, style = MaterialTheme.typography.bodySmall)

        if (entry.members.isNotEmpty()) {
            Text(
                entry.members.joinToString(", "),
                style = MaterialTheme.typography.bodySmall,
                modifier = Modifier.semantics {
                    contentDescription = "Covered by this licence: ${entry.members.joinToString(", ")}"
                },
            )
        }

        Column(Modifier.verticalScroll(rememberScrollState())) {
            Text(
                entry.text,
                style = MaterialTheme.typography.bodySmall.copy(fontFamily = FontFamily.Monospace),
                modifier = Modifier.horizontalScroll(rememberScrollState()),
            )
        }
    }
}
