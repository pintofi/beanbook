"""The files a new ledger starts with are read by real Beancount and Fava without an error.

The text is generated by `LedgerBlueprint` (core-domain) and held in `fixtures/new-ledger/`; a
Kotlin test fails if the generator and those files drift apart, and this one fails if what they
hold is something Beancount would not accept. A new project has a `documents/` folder, which the
app creates and git cannot hold, so the copy under test gets one.
"""

import json
import shutil
import sys
import tempfile
import unittest
from pathlib import Path

REPO = Path(__file__).resolve().parents[4]
sys.path.insert(0, str(REPO / "engine-local" / "src" / "main" / "python"))

import ledger  # noqa: E402

HELD = REPO / "fixtures" / "new-ledger"


def load(case):
    with tempfile.TemporaryDirectory() as directory:
        target = Path(directory) / case
        shutil.copytree(HELD / case, target)
        (target / "documents").mkdir()
        return json.loads(ledger.inspect(str(target / "main.beancount")))


class NewLedgerGoldenTest(unittest.TestCase):
    def test_every_held_case_reads_without_an_error(self):
        cases = sorted(p.name for p in HELD.iterdir() if p.is_dir())
        self.assertTrue(cases, "no cases held")
        for case in cases:
            with self.subTest(case=case):
                payload = load(case)
                self.assertEqual([], payload["errors"], case)

    def test_the_household_opening_balances_are_padded_and_asserted(self):
        payload = load("household")
        accounts = {row["name"]: row for row in payload["accounts"]}
        checking = accounts["Assets:Bank:Checking"]["positions"]
        card = accounts["Liabilities:CreditCard"]["positions"]
        self.assertEqual([{"number": "1250.00", "currency": "EUR"}], checking)
        self.assertEqual([{"number": "-310.40", "currency": "EUR"}], card)
        self.assertEqual(["EUR"], payload["operating_currency"])

    def test_commodities_are_declared_with_their_names(self):
        payload = load("household")
        self.assertEqual(["EUR", "USD"], sorted(payload["commodities"]))


if __name__ == "__main__":
    unittest.main()
